// Project-level operations: storyboard -> scene slots, talent framing,
// transcription and captions. Every step that can be computed is computed,
// so Claude only writes the creative parts (storyboard and scene designs).
import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import {
  ROOT,
  LAYOUT,
  FPS,
  die,
  warn,
  hf,
  run,
  probeMedia,
  readJson,
  fixed,
  replaceBetween,
  replaceStyle,
  escapeHtml,
} from "./common.mjs";
import { loadBrand, fontStack, captionColors, contrast } from "./brand.mjs";

const SCENE_ID = /^scene-[a-z0-9-]{1,40}$/;

export function readStoryboard(dir) {
  const file = join(dir, "storyboard.json");
  if (!existsSync(file)) die(`falta ${file}`);
  return readJson(file);
}

function validateScenes(board) {
  const scenes = [...(board.scenes ?? [])].sort((a, b) => a.start - b.start);
  if (!scenes.length) die("storyboard.json no tiene escenas");
  const ids = new Set();
  let cursor = 0;
  for (const s of scenes) {
    if (!SCENE_ID.test(s.id ?? "")) die(`id de escena inválido "${s.id}": usa scene-<algo> en minúsculas`);
    if (ids.has(s.id)) die(`id de escena repetido: ${s.id}`);
    ids.add(s.id);
    if (!(s.end > s.start) || s.start < 0) die(`${s.id}: necesita 0 <= start < end`);
    if (s.end > board.duration + 1 / FPS) die(`${s.id}: termina en ${s.end}s, después del clip (${board.duration}s)`);
    if (s.start < cursor - 1 / FPS) die(`${s.id} se superpone con la escena anterior (empieza en ${s.start}s, la anterior acaba en ${cursor}s)`);
    if (s.start > cursor + 0.25) warn(`hueco sin escena de ${cursor.toFixed(2)}s a ${s.start}s: se verá solo el fondo de la marca`);
    cursor = s.end;
  }
  if (cursor < board.duration - 0.25) warn(`desde ${cursor.toFixed(2)}s hasta el final (${board.duration}s) no hay escena`);
  return scenes;
}

function sceneSlot(s) {
  return `
      <div
        id="el-${s.id}"
        class="zone-illus"
        data-composition-id="${s.id}"
        data-composition-src="compositions/${s.id}.html"
        data-start="${fixed(s.start)}"
        data-duration="${fixed(s.end - s.start)}"
        data-track-index="2"
        data-width="${LAYOUT.illus.w}"
        data-height="${LAYOUT.illus.h}"
      ></div>`;
}

/**
 * Rewrite the scene slots from storyboard.json and scaffold missing scene
 * files. Ids listed in `reset` are scaffolded again even if they exist.
 */
export function buildScenes(dir, reset = []) {
  const board = readStoryboard(dir);
  const brand = loadBrand(board.brand);
  const scenes = validateScenes(board);
  const indexFile = join(dir, "index.html");
  const html = replaceBetween(
    readFileSync(indexFile, "utf8"),
    "<!-- SCENES:START (generated by `npm run scenes` from storyboard.json) -->",
    "<!-- SCENES:END -->",
    `${scenes.map(sceneSlot).join("")}\n      `,
  );
  writeFileSync(indexFile, html);

  const template = readFileSync(join(ROOT, "template", "compositions", "scene.html"), "utf8");
  const created = [];
  for (const s of scenes) {
    const file = join(dir, "compositions", `${s.id}.html`);
    if (existsSync(file) && !reset.includes(s.id)) continue;
    const content = template
      .replaceAll("{{SCENE_ID}}", s.id)
      .replaceAll("{{KICKER}}", escapeHtml(s.kicker ?? brand.handle))
      .replaceAll("{{TITLE}}", escapeHtml(s.title ?? s.intent ?? ""))
      .replaceAll("{{FONT_DISPLAY_STACK}}", fontStack(brand.fonts.display))
      .replaceAll("{{FONT_BODY_STACK}}", fontStack(brand.fonts.body));
    mkdirSync(join(dir, "compositions"), { recursive: true });
    writeFileSync(file, content);
    created.push(s.id);
  }
  return { scenes, created };
}

/**
 * Place the face (center, in source pixels) at the middle of the visible face
 * band (y 1000-1248) by moving object-position; the layout itself never moves.
 */
export function reframe(dir, faceX, faceY) {
  const src = probeMedia(join(dir, "assets", "source.mp4"));
  const { w: boxW, h: boxH, y: boxY } = LAYOUT.video;
  const scale = Math.max(boxW / src.width, boxH / src.height);
  const scaledW = src.width * scale;
  const scaledH = src.height * scale;
  const targetY = (LAYOUT.face.y0 + LAYOUT.face.y1) / 2 - boxY;
  const clamp = (v, max) => Math.min(Math.max(v, 0), max);
  const offX = clamp(faceX * scale - boxW / 2, scaledW - boxW);
  const offY = clamp(faceY * scale - targetY, scaledH - boxH);
  const posX = scaledW > boxW ? (offX / (scaledW - boxW)) * 100 : 50;
  const posY = scaledH > boxH ? (offY / (scaledH - boxH)) * 100 : 50;
  const faceCanvasY = boxY + faceY * scale - offY;

  const indexFile = join(dir, "index.html");
  const css = `      :root {\n        --talent-x: ${posX.toFixed(2)}%;\n        --talent-y: ${posY.toFixed(2)}%;\n      }`;
  writeFileSync(indexFile, replaceStyle(readFileSync(indexFile, "utf8"), "talent", css));
  return { posX, posY, faceCanvasY: Math.round(faceCanvasY), inBand: faceCanvasY >= LAYOUT.face.y0 && faceCanvasY <= LAYOUT.face.y1 };
}

/** Local transcription (Parakeet when installed, else Whisper) into transcript.json. */
export function transcribe(dir, lang) {
  const wav = join(dir, "assets", "audio.wav");
  run("ffmpeg", ["-y", "-v", "error", "-i", join(dir, "assets", "source.mp4"), "-vn", "-ac", "1", "-ar", "16000", wav]);
  const res = hf(["transcribe", wav, "--dir", dir, "--language", lang], { allowFail: true });
  return res.status === 0 && existsSync(join(dir, "transcript.json"));
}

function readWords(dir) {
  const file = join(dir, "transcript.json");
  if (!existsSync(file)) return null;
  const raw = readJson(file);
  const list = Array.isArray(raw) ? raw : raw.words ?? (raw.segments ?? []).flatMap((s) => s.words ?? []);
  return list
    .map((w) => ({ text: String(w.text ?? w.word ?? "").trim(), start: Number(w.start), end: Number(w.end) }))
    .filter((w) => w.text && Number.isFinite(w.start) && Number.isFinite(w.end));
}

// Caption sizing. One line per group: two lines at a readable size do not fit
// in the 140 px band. CHAR_EM is a conservative average advance for a bold
// sans glyph; the layout audit in `npm run check` catches the rare overflow.
const MAX_WORDS = 4;
const PAUSE = 0.3; // a silence this long closes a group
const HOLD = 0.25; // keep a group up a bit after its last word...
const TAIL = 0.6; // ...and the last one a bit longer
const CHAR_EM = 0.6;
const BOX_PAD_X = 28;
const MAX_TEXT_W = LAYOUT.textSafe.x1 - LAYOUT.textSafe.x0 - 2 * BOX_PAD_X;
const MIN_SIZE = 56; // ~40 px cap height, the minimum in docs/instagram-reels.md

function applyCase(text, mode) {
  if (mode === "upper") return text.toLocaleUpperCase("es");
  if (mode === "lower") return text.toLocaleLowerCase("es");
  return text;
}

function groupWords(words, size, duration) {
  const maxChars = Math.floor(MAX_TEXT_W / (size * CHAR_EM));
  const groups = [];
  let current = [];
  const flush = () => {
    if (current.length) groups.push(current);
    current = [];
  };
  words.forEach((word, i) => {
    const candidate = [...current, word];
    const length = candidate.map((w) => w.text).join(" ").length;
    if (current.length && (candidate.length > MAX_WORDS || length > maxChars)) {
      flush();
      current = [word];
    } else {
      current.push(word);
    }
    const next = words[i + 1];
    if (!next || /[.,;:!?…]$/.test(word.text) || next.start - word.end >= PAUSE) flush();
  });
  flush();

  return groups.map((g, i) => {
    const next = groups[i + 1];
    const start = g[0].start;
    const last = g[g.length - 1];
    const end = next ? Math.min(next[0].start, last.end + HOLD) : Math.min(duration, last.end + TAIL);
    const text = g.map((w) => w.text).join(" ");
    const fit = Math.floor(MAX_TEXT_W / (text.length * CHAR_EM));
    return {
      start: fixed(start),
      end: fixed(Math.max(end, start + 2 / FPS)),
      size: Math.max(MIN_SIZE, Math.min(size, fit)),
      words: g.map((w, wi) => {
        const nextWord = g[wi + 1];
        const off = nextWord && nextWord.start - w.end < PAUSE ? nextWord.start : w.end;
        return { text: w.text, on: fixed(w.start), off: fixed(Math.max(off, w.start + 1 / FPS)) };
      }),
    };
  });
}

/** Generate compositions/captions.html from transcript.json and the brand. */
export function buildCaptions(dir) {
  const board = readStoryboard(dir);
  const brand = loadBrand(board.brand);
  const words = readWords(dir) ?? [];
  const cap = brand.captions;
  const colors = captionColors(brand);
  const groups = groupWords(
    words.map((w) => ({ ...w, text: applyCase(w.text, cap.case) })),
    cap.size,
    board.duration,
  );

  if (colors.box) {
    for (const [label, color] of [["texto", colors.ink], ["resaltado", colors.highlight]]) {
      const ratio = contrast(color, colors.box);
      if (ratio < 4.5) warn(`contraste ${label}/caja de subtítulos ${ratio.toFixed(2)}:1 (< 4.5:1). Ajusta captions en brands/${brand.name}.json`);
    }
  }
  for (const g of groups) {
    if (g.size === MIN_SIZE && g.words.map((w) => w.text).join(" ").length * MIN_SIZE * CHAR_EM > MAX_TEXT_W) {
      warn(`grupo de subtítulos muy largo en ${g.start}s ("${g.words.map((w) => w.text).join(" ")}"): revisa que no se salga`);
    }
  }

  const boxCss = colors.box
    ? `background: ${colors.box};`
    : "background: transparent; text-shadow: 0 3px 0 rgba(0, 0, 0, 0.85), 0 0 18px rgba(0, 0, 0, 0.75);";
  const markup = groups
    .map(
      (g, gi) =>
        `        <div class="cap-group" id="captions-g${gi}"><div class="cap-box" style="font-size: ${g.size}px">` +
        g.words.map((w, wi) => `<span id="captions-g${gi}-w${wi}">${escapeHtml(w.text)}</span>`).join("") +
        "</div></div>",
    )
    .join("\n");
  const data = JSON.stringify(groups.map((g) => [g.start, g.end, g.words.map((w) => [w.on, w.off])]));

  const html = `<!doctype html>
<!--
  Generated by \`npm run captions\` from transcript.json and brands/${brand.name}.json.
  Do not edit: fix the words in transcript.json (keep start/end) and run it again.
-->
<html lang="es">
  <head>
    <meta charset="UTF-8" />
  </head>
  <body>
    <template id="captions-template">
      <style>
        #root {
          position: absolute;
          inset: 0;
        }
        .cap-group {
          position: absolute;
          left: ${LAYOUT.textSafe.x0}px;
          right: ${LAYOUT.canvas.w - LAYOUT.textSafe.x1}px;
          top: 0;
          bottom: 0;
          display: flex;
          align-items: center;
          justify-content: center;
          opacity: 0;
        }
        .cap-box {
          display: flex;
          flex-wrap: nowrap;
          gap: 0.26em;
          padding: 14px ${BOX_PAD_X}px 16px;
          border-radius: 18px;
          white-space: nowrap;
          font-family: ${fontStack(brand.fonts.body)};
          font-weight: ${cap.weight ?? 800};
          line-height: 1.1;
          color: ${colors.ink};
          ${boxCss}
        }
      </style>
      <div id="root" data-composition-id="captions" data-width="${LAYOUT.captions.w}" data-height="${LAYOUT.captions.h}">
${markup}
      </div>
      <script>
        (function () {
          const tl = gsap.timeline({ paused: true });
          const groups = ${data};
          groups.forEach(function (g, gi) {
            const group = document.getElementById("captions-g" + gi);
            tl.set(group, { opacity: 1 }, g[0]);
            tl.fromTo(
              group.firstElementChild,
              { scale: 0.94 },
              { scale: 1, duration: 0.12, ease: "power2.out", immediateRender: false },
              g[0],
            );
            tl.set(group, { opacity: 0 }, g[1]);
            g[2].forEach(function (w, wi) {
              const word = document.getElementById("captions-g" + gi + "-w" + wi);
              tl.set(word, { color: "${colors.highlight}" }, w[0]);
              tl.set(word, { color: "${colors.ink}" }, w[1]);
            });
          });
          window.__timelines["captions"] = tl;
        })();
      </script>
    </template>
  </body>
</html>
`;
  writeFileSync(join(dir, "compositions", "captions.html"), html);
  return { groups: groups.length, words: words.length };
}
